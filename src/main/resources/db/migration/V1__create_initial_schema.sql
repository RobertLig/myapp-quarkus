CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    email VARCHAR(255),
    password VARCHAR(255),
    salt VARCHAR(255),
    ageRange VARCHAR(255),
    gender VARCHAR(255),
    phone VARCHAR(255),
    photoUrl VARCHAR(255),
    role VARCHAR(255),
    emailVerified BOOLEAN NOT NULL,
    verificationToken VARCHAR(255),
    resetPasswordToken VARCHAR(255),
    createdAt TIMESTAMP(6),
    updatedAt TIMESTAMP(6),
    locale VARCHAR(255),
    googleId VARCHAR(255),
    termsAccepted BOOLEAN NOT NULL
);

CREATE TABLE announcement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(255) NOT NULL,
    dimensions_width DOUBLE PRECISION,
    dimensions_height DOUBLE PRECISION,
    dimensions_length DOUBLE PRECISION,
    weight_value DOUBLE PRECISION,
    postingPlace VARCHAR(255),
    postingLatitude DOUBLE PRECISION,
    postingLongitude DOUBLE PRECISION,
    receptionPlace VARCHAR(255),
    receptionLatitude DOUBLE PRECISION,
    receptionLongitude DOUBLE PRECISION,
    postingDateTime TIMESTAMP(6),
    receptionDateTime TIMESTAMP(6),
    user_id BIGINT,
    createdAt TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_announcement_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE conversation (
    id BIGINT PRIMARY KEY,
    announcement_id BIGINT,
    createdAt TIMESTAMP(6),
    type VARCHAR(255),
    CONSTRAINT fk_conversation_announcement FOREIGN KEY (announcement_id) REFERENCES announcement (id)
);

CREATE TABLE conversationparticipant (
    id BIGINT PRIMARY KEY,
    conversation_id BIGINT,
    user_id BIGINT,
    joinedAt TIMESTAMP(6),
    deletedAt TIMESTAMP(6),
    lastReadMessageId BIGINT,
    unreadCount INTEGER,
    CONSTRAINT fk_conversation_participant_conversation FOREIGN KEY (conversation_id) REFERENCES conversation (id),
    CONSTRAINT fk_conversation_participant_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE message (
    id BIGINT PRIMARY KEY,
    conversation_id BIGINT,
    sender_id BIGINT,
    content VARCHAR(255),
    createdAt TIMESTAMP(6),
    deletedForRecipientAt TIMESTAMP(6),
    deletedAt TIMESTAMP(6),
    CONSTRAINT fk_message_conversation FOREIGN KEY (conversation_id) REFERENCES conversation (id),
    CONSTRAINT fk_message_sender FOREIGN KEY (sender_id) REFERENCES users (id)
);

CREATE TABLE messageevent (
    id BIGINT PRIMARY KEY,
    message_id BIGINT,
    user_id BIGINT,
    type VARCHAR(255),
    createdAt TIMESTAMP(6),
    CONSTRAINT fk_message_event_message FOREIGN KEY (message_id) REFERENCES message (id),
    CONSTRAINT fk_message_event_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE message_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    url VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    size BIGINT NOT NULL,
    createdAt TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_message_attachments_message FOREIGN KEY (message_id) REFERENCES message (id),
    CONSTRAINT fk_message_attachments_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE message_reactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    reaction VARCHAR(255) NOT NULL,
    createdAt TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_message_reactions_message_user UNIQUE (message_id, user_id),
    CONSTRAINT fk_message_reactions_message FOREIGN KEY (message_id) REFERENCES message (id),
    CONSTRAINT fk_message_reactions_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE userblock (
    id BIGINT PRIMARY KEY,
    blocker_id BIGINT,
    blocked_id BIGINT,
    createdAt TIMESTAMP(6),
    CONSTRAINT fk_user_block_blocker FOREIGN KEY (blocker_id) REFERENCES users (id),
    CONSTRAINT fk_user_block_blocked FOREIGN KEY (blocked_id) REFERENCES users (id)
);

CREATE TABLE photo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url VARCHAR(255),
    position INTEGER NOT NULL,
    announcement_id BIGINT,
    createdAt TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_photo_announcement FOREIGN KEY (announcement_id) REFERENCES announcement (id)
);

CREATE TABLE stop (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address VARCHAR(255),
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    position INTEGER NOT NULL,
    announcement_id BIGINT,
    CONSTRAINT fk_stop_announcement FOREIGN KEY (announcement_id) REFERENCES announcement (id)
);

CREATE TABLE announcementtranslation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    language VARCHAR(255),
    title VARCHAR(255),
    description VARCHAR(255),
    announcement_id BIGINT,
    CONSTRAINT fk_announcement_translation_announcement FOREIGN KEY (announcement_id) REFERENCES announcement (id)
);

CREATE SEQUENCE conversation_seq INCREMENT BY 50;
CREATE SEQUENCE conversationparticipant_seq INCREMENT BY 50;
CREATE SEQUENCE message_seq INCREMENT BY 50;
CREATE SEQUENCE messageevent_seq INCREMENT BY 50;
CREATE SEQUENCE userblock_seq INCREMENT BY 50;

CREATE INDEX idx_announcement_user_id ON announcement (user_id);
CREATE INDEX idx_conversation_announcement_id ON conversation (announcement_id);
CREATE INDEX idx_conversation_participant_user_id ON conversationparticipant (user_id);
CREATE INDEX idx_conversation_participant_conversation_id ON conversationparticipant (conversation_id);
CREATE INDEX idx_message_conversation_id ON message (conversation_id);
CREATE INDEX idx_message_sender_id ON message (sender_id);
CREATE INDEX idx_message_event_message_id ON messageevent (message_id);
CREATE INDEX idx_message_event_user_id ON messageevent (user_id);
CREATE INDEX idx_message_attachments_message_id ON message_attachments (message_id);
CREATE INDEX idx_message_attachments_user_id ON message_attachments (user_id);
CREATE INDEX idx_message_reactions_user_id ON message_reactions (user_id);
CREATE INDEX idx_user_block_blocker_id ON userblock (blocker_id);
CREATE INDEX idx_user_block_blocked_id ON userblock (blocked_id);
CREATE INDEX idx_photo_announcement_id ON photo (announcement_id);
CREATE INDEX idx_stop_announcement_id ON stop (announcement_id);
CREATE INDEX idx_announcement_translation_announcement_id ON announcementtranslation (announcement_id);
